import json
import uuid
import os
import time
from typing import TypedDict, Annotated
from pydantic import BaseModel, Field

from dotenv import load_dotenv
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import ChatPromptTemplate

# Import our advanced agent workflow
from agent_workflow_advanced_rag import app as agent_app

load_dotenv()

# --- EVALUATION AGENT SETUP ---
# Using a highly capable model for judging code quality
eval_llm = ChatGoogleGenerativeAI(model="gemini-2.5-pro", temperature=0.0)

class EvalResult(BaseModel):
    score: int = Field(description="A score from 1 to 5 indicating the quality and correctness of the generated code compared to the instruction and ground truth.")
    reasoning: str = Field(description="Detailed reasoning for the given score, highlighting strengths, missing resources, or security flaws.")

eval_prompt = ChatPromptTemplate.from_messages([
    ("system", 
    "You are an expert Cloud Architect and HashiCorp certified Terraform Associate acting as a strict code judge.\n"
    "Your job is to evaluate Terraform code generated by an AI agent against a user instruction and a ground-truth reference.\n\n"
    "Scoring Rubric (1-5):\n"
    "5 - Excellent: Code is functionally correct, follows best practices (e.g., security, naming), and completely fulfills the instruction. It may differ from the ground truth in styling or added security (which is good), but the core infrastructure is perfectly sound.\n"
    "4 - Good: Code works and fulfills the instruction, but might miss minor best practices or have slight deviations from optimal design.\n"
    "3 - Acceptable: Code partially fulfills the requirement or has minor syntax/logical issues that would require slight manual fixing.\n"
    "2 - Poor: Code misses major requirements, introduces security risks, or uses incorrect resource types.\n"
    "1 - Failure: Code is completely wrong, invalid, or no code was generated.\n\n"
    "Output your evaluation using the required structured format."
    ),
    ("human", 
    "Instruction: {instruction}\n\n"
    "Ground Truth Reference:\n```terraform\n{ground_truth}\n```\n\n"
    "Agent Generated Code:\n```terraform\n{generated_code}\n```\n\n"
    "Evaluate the generated code."
    )
])

eval_chain = eval_prompt | eval_llm.with_structured_output(EvalResult)

# --- RUN EVALUATION ---
def run_evaluation(dataset_path="iac_eval.jsonl"):
    print("🚀 Starting Agentic Evaluation against IaC Benchmark...\n")
    
    with open(dataset_path, 'r') as f:
        dataset = [json.loads(line) for line in f if line.strip()]

    total_score = 0
    max_possible_score = len(dataset) * 5
    results_summary = []

    for i, data in enumerate(dataset):
        instruction = data['instruction']
        ground_truth = data['output']
        
        print(f"[{i+1}/{len(dataset)}] Evaluating Instruction: '{instruction}'")
        
        # 1. Run the instruction through our Advanced RAG Agent
        thread_id = str(uuid.uuid4()) # Unique thread for each eval
        config = {"configurable": {"thread_id": thread_id}}
        
        initial_state = {
            "user_request": instruction,
            "messages": [],
            "retrieved_context": "",
            "citations": [],
            "terraform_code": {},
            "validation_errors": "",
            "is_valid": False,
            "retry_count": 0,
            "cost_estimate": ""
        }
        
        print("   Running agent workflow (this may take a moment)...")
        try:
            # We use invoke here. In a large eval set, you might use async ainvoke for parallelization.
            final_state = agent_app.invoke(initial_state, config=config)
            
            # Extract generated code
            generated_files = final_state.get("terraform_code", {})
            generated_code_str = "\n".join([f"--- {k} ---\n{v}" for k, v in generated_files.items()])
            
            if not generated_files:
                generated_code_str = "NO CODE GENERATED"
                
            is_valid = final_state.get("is_valid", False)
            
        except Exception as e:
            print(f"   Agent workflow failed: {e}")
            generated_code_str = f"ERROR: {e}"
            is_valid = False

        # 2. Run LLM-as-a-Judge Evaluation
        print("   Running Eval Agent Judge...")
        try:
            eval_result = eval_chain.invoke({
                "instruction": instruction,
                "ground_truth": ground_truth,
                "generated_code": generated_code_str
            })
            
            score = eval_result.score
            reasoning = eval_result.reasoning
        except Exception as e:
            print(f"   Eval Agent failed: {e}")
            score = 1
            reasoning = f"Eval failed due to error: {e}"

        total_score += score
        
        print(f"   Score: {score}/5")
        print(f"   Reasoning: {reasoning}")
        print(f"   Validation Passed: {is_valid}")
        print("-" * 50)
        
        results_summary.append({
            "instruction": instruction,
            "score": score,
            "valid": is_valid,
            "reasoning": reasoning
        })
        
        # Rate limit protection for free tier
        time.sleep(2)

    # --- FINAL REPORT ---
    print("\n" + "="*50)
    print("🏆 FINAL BENCHMARK REPORT")
    print("="*50)
    print(f"Total Score: {total_score} / {max_possible_score}")
    print(f"Average Score: {total_score / len(dataset):.2f} / 5.0")
    
    valid_count = sum(1 for r in results_summary if r['valid'])
    print(f"Code Validity Rate: {valid_count}/{len(dataset)} ({(valid_count/len(dataset))*100:.1f}%)")
    print("="*50)
    
    # Optionally save results to a file
    with open("eval_results_report.json", "w") as f:
        json.dump(results_summary, f, indent=2)
    print("Detailed report saved to 'eval_results_report.json'")

if __name__ == "__main__":
    if not os.path.exists("iac_eval.jsonl"):
        print("Error: iac_eval.jsonl not found in the current directory.")
    else:
        run_evaluation()
